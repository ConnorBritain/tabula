// Pin the public library's generated route artifact. This copies metadata, never teaching content.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export function routeSnapshot(data, { cutover = false } = {}) {
  if (data.version !== 1 || !data.articles || !data.legacy || !data.tracks) throw new Error('Expected learning routes version 1.');
  if (cutover && data.releaseReady !== true) throw new Error('Library cutover needs a reviewed, release-ready route artifact.');
  const path = (value) => typeof value === 'string' && /^\/learn\/(?:[a-z0-9-]+\/)*$/.test(value);
  const articles = {};
  for (const [id, a] of Object.entries(data.articles)) {
    if (!/^[a-z0-9-]+$/.test(id) || !path(a.path)) throw new Error(`Invalid learning article: ${id}`);
    articles[id] = { path: a.path, title: a.title, event: a.event };
  }
  const events = {};
  for (const [id, e] of Object.entries(data.events || {})) {
    if (!/^[a-z0-9-]+$/.test(id) || !path(e.path)) throw new Error(`Invalid learning event: ${id}`);
    events[id] = { path: e.path, title: e.title };
  }
  // The three shipped debate formats always have event hubs, even while their lessons are being written.
  for (const [id, title] of [['policy', 'Policy'], ['lincoln-douglas', 'Lincoln-Douglas'], ['public-forum', 'Public Forum']]) {
    events[id] ||= { path: `/learn/debate/${id}/`, title };
  }
  const legacy = {};
  for (const [slug, target] of Object.entries(data.legacy)) {
    if (!/^[a-z0-9-]+$/.test(slug) || !path(target)) throw new Error(`Invalid learning alias: ${slug}`);
    legacy[slug] = target;
  }
  const tracks = {};
  for (const [id, t] of Object.entries(data.tracks)) {
    if (!/^[a-z0-9-]+$/.test(id) || !path(t.path)) throw new Error(`Invalid learning track: ${id}`);
    tracks[id] = { path: t.path };
  }
  const oldTracks = {};
  for (const [oldId, id] of Object.entries(data.legacyProgress?.tracks || {})) {
    if (!/^[a-z0-9-]+$/.test(oldId) || !tracks[id]) throw new Error(`Invalid learning course alias: ${oldId}`);
    oldTracks[oldId] = tracks[id].path;
  }
  const sourceDigest = createHash('sha256').update(JSON.stringify(data)).digest('hex');
  return { version: 1, enabled: cutover, releaseReady: data.releaseReady === true, sourceDigest, articles, events, legacy, oldTracks };
}

export function snapshotScript(snapshot) {
  return '// Generated by scripts/sync-learning-routes.mjs. Source digest pins the public library metadata.\n' +
    '(function (root) {\n  const routes = ' + JSON.stringify(snapshot, null, 2) + ';\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = routes;\n" +
    '  else (root.PolicyLogicParts ||= {}).learningRoutes = routes;\n' +
    "})(typeof window !== 'undefined' ? window : globalThis);\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const input = process.argv.slice(2).find((a) => !a.startsWith('--'));
  if (!input) throw new Error('Usage: node scripts/sync-learning-routes.mjs <routes.json> [--cutover]');
  const snapshot = routeSnapshot(JSON.parse(readFileSync(input, 'utf8')), { cutover: process.argv.includes('--cutover') });
  const exporter = readFileSync(join(dirname(input), 'runtime', 'export.js'), 'utf8');
  snapshot.exporterDigest = createHash('sha256').update(exporter).digest('hex');
  writeFileSync(new URL('../vendor/learning-export.js', import.meta.url), exporter);
  writeFileSync(new URL('../logic/learning-routes.js', import.meta.url), snapshotScript(snapshot));
  console.log(`Pinned ${Object.keys(snapshot.articles).length} articles; cutover ${snapshot.enabled ? 'on' : 'off'}; source ${snapshot.sourceDigest}.`);
}
