// Comment kit: builds events/comment-kit/kit-data.js from starters.json and words.json.
// Run with: node events/comment-kit/build-data.mjs   (after any change to either JSON file).
//
// Why a built JS file and not the JSON itself: the page loads only static ES module imports and the event loader
// (events/build-sw.mjs crawls them for the offline cache). A JSON import needs import attributes, which older
// tablets cannot parse, and a fetch() would need its own cache entry. A plain module works on every device, offline.
// events/comment-kit/kit.test.mjs fails while kit-data.js is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const HERE = new URL('./', import.meta.url);
export const OUT = new URL('kit-data.js', HERE);
const json = (name) => JSON.parse(readFileSync(new URL(name, HERE), 'utf8'));

/** The text of kit-data.js for the JSON files as they are now. */
export function kitDataSource() {
  const starters = json('starters.json');
  const words = json('words.json');
  return '// Generated by events/comment-kit/build-data.mjs from starters.json and words.json. Do not edit:\n'
    + '// change the JSON, then run node events/comment-kit/build-data.mjs.\n'
    + 'export const STARTERS = ' + JSON.stringify(starters, null, 2) + ';\n'
    + 'export const WORDS = ' + JSON.stringify(words, null, 2) + ';\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, kitDataSource());
  console.log('Wrote ' + fileURLToPath(OUT));
}
