// Writes events/prototype/data.js from the event files, the profile files and the EVENTS.md §7 check list.
// The prototype reads data.js (a plain script), so it opens from disk with no server and makes no network call.
// Run after any change to events/defs/ or events/profiles/: node events/prototype/build-data.mjs
// A test (events/events-data.test.mjs) fails if data.js is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { readCheckList } from '../check-list.mjs';

const at = (p) => new URL(p, import.meta.url);
const readJson = (p) => JSON.parse(readFileSync(at(p), 'utf8'));

/** The text of data.js: the latest version of each event and profile, plus the check labels. */
export function dataSource() {
  const pub = readJson('../published.json');
  const latest = (files, dir) => {
    const byId = new Map();
    for (const f of files) {
      const d = readJson(`../${dir}/${f}`);
      if (!byId.has(d.id) || byId.get(d.id).version < d.version) byId.set(d.id, d);
    }
    return [...byId.values()];
  };
  const data = {
    events: latest(pub.defs, 'defs'),
    profiles: latest(pub.profiles, 'profiles'),
    checks: Object.fromEntries(readCheckList().map((c) => [c.id, c.label])),
  };
  return '// Generated by build-data.mjs from events/defs, events/profiles and docs/events/EVENTS.md §7. Do not edit.\n'
    + 'window.TABULA_EVENTS_DATA = ' + JSON.stringify(data, null, 1) + ';\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(at('data.js'), dataSource());
  console.log('Wrote events/prototype/data.js');
}
