// Tabula Speech Events: builds events/sw-files.js, the release the service worker caches (docs/events/LANDING.md §4.1,
// step E2). Run with: node events/build-sw.mjs   (after any change to a file the events page loads).
//
// The file list is not typed by hand. It is found from the real files, the same way the browser finds them:
//   - events/index.html: every <script src> and <link href>;
//   - every JS module reached from there: each static import (import ... from '...', import '...', export ... from);
//   - every CSS file: each url(...) and @import;
//   - the event data: events/js/data.js's own loader (loadEventData), run with a reader that notes each file it asks for;
//   - every workspace module in the round-type router's registry (events/js/workspaces.js WORKSPACES), and what each
//     one imports. Today workspaces.js also imports them statically, so the main crawl finds them too; this seed keeps
//     them cached once a workspace loads on demand (EXPERIENCE.md §9).
// The release name is a content hash of that list (each path and its bytes). A change to any cached byte changes the
// hash, so sw-files.js changes, so the browser installs a new worker and replaces the whole cache at once.
// events/sw.test.mjs fails while sw-files.js is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { loadEventData } from './js/data.js';
import { WORKSPACES } from './js/workspaces.js';

const EVENTS = new URL('./', import.meta.url);
const ROOT = new URL('../', import.meta.url);
export const OUT = new URL('sw-files.js', EVENTS);

const read = (u) => readFileSync(u, 'utf8');
// Only a plain relative or root path is a file of this site. A full URL, a data: URL or a fragment is not followed.
const local = (ref) => ref && !/^[a-z][a-z0-9+.-]*:|^\/\/|^#/i.test(ref);
const resolve = (ref, from) => { const u = new URL(ref, from); u.search = ''; u.hash = ''; return u; };

const htmlRefs = (src) => [...src.matchAll(/<(?:script|link)\b[^>]*?\b(?:src|href)\s*=\s*"([^"]+)"/gi)].map((m) => m[1]);
const cssRefs = (src) => [
  ...[...src.matchAll(/url\(\s*(['"]?)([^'")]+)\1\s*\)/gi)].map((m) => m[2]),
  ...[...src.matchAll(/@import\s+(['"])([^'"]+)\1/gi)].map((m) => m[2]),
];
// A static import or re-export. Each line that starts an import must give a path, or the crawl stops: a form it cannot
// read would leave a file out of the cache with no warning.
export const jsRefs = (src, path) => {
  const refs = [...src.matchAll(/^\s*(?:import|export)\b[^'"`;]*?\bfrom\s*['"]([^'"]+)['"]|^\s*import\s*['"]([^'"]+)['"]/gm)].map((m) => m[1] || m[2]);
  const imports = (src.match(/^\s*import\b(?!\s*[(.])/gm) || []).length;
  const fromImports = refs.length - (src.match(/^\s*export\b[^'"`;]*?\bfrom\s*['"]/gm) || []).length;
  if (imports !== fromImports) throw new Error(path + ': an import line the crawl cannot read (' + imports + ' import lines, ' + fromImports + ' paths found)');
  return refs;
};

/** Every file the events page loads, as repo-root paths ('events/index.html', 'core/ui.js'), sorted. */
export async function pageFiles() {
  const seen = new Set();
  const registry = new URL('js/workspaces.js', EVENTS);
  const todo = [new URL('index.html', EVENTS), ...Object.values(WORKSPACES).map((p) => resolve(p, registry))];
  while (todo.length) {
    const u = todo.pop();
    const path = u.href.slice(ROOT.href.length);
    if (seen.has(path)) continue;
    if (!u.href.startsWith(ROOT.href)) throw new Error('the events page loads a file outside the repo: ' + u.href);
    seen.add(path);
    const ext = path.slice(path.lastIndexOf('.'));
    if (!['.html', '.js', '.css'].includes(ext)) continue;
    const src = read(u);
    const refs = ext === '.html' ? htmlRefs(src) : ext === '.css' ? cssRefs(src) : jsRefs(src, path);
    for (const r of refs) if (local(r)) todo.push(resolve(r, u));
  }
  // The event data: ask the real loader which files it reads.
  await loadEventData(async (p) => { seen.add('events/' + p); return JSON.parse(read(new URL(p, EVENTS))); });
  return [...seen].sort();
}

/** A repo-root path as the worker names it: relative to events/sw.js ('index.html', '../core/ui.js'). */
export const forWorker = (path) => (path.startsWith('events/') ? path.slice('events/'.length) : '../' + path);

/** The release name: the first 16 hex digits of a SHA-256 over each path and its bytes, in list order. */
// bytesOf(path) reads a repo-root path (the disk by default; tests pass their own).
export function releaseHash(paths, bytesOf = (p) => readFileSync(new URL(p, ROOT))) {
  const h = createHash('sha256');
  for (const p of paths) { h.update(p + '\0'); h.update(bytesOf(p)); h.update('\0'); }
  return h.digest('hex').slice(0, 16);
}

/** The text of events/sw-files.js for the files on disk now. */
export async function swFilesSource() {
  const paths = await pageFiles();
  return [
    '// Generated by events/build-sw.mjs from the files the events page loads. Do not edit: run node events/build-sw.mjs.',
    '// The service worker (events/sw.js) reads this with importScripts. Paths are relative to events/sw.js.',
    "self.TABULA_EVENTS_RELEASE = '" + releaseHash(paths) + "';",
    'self.TABULA_EVENTS_FILES = ' + JSON.stringify(paths.map(forWorker), null, 2) + ';',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, await swFilesSource());
  console.log('Wrote ' + fileURLToPath(OUT));
}
